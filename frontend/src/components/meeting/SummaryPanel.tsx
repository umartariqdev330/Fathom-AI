import { CircleCheck, Lightbulb, ListChecks, Sparkles } from 'lucide-react'
import type { Summary } from '../../types'
import { Badge, EmptyState } from '../ui'

export function SummaryPanel({ summary }: { summary: Summary | null }) {
  if (!summary) {
    return (
      <EmptyState
        icon={<Sparkles size={22} />}
        title="No summary yet"
        description="This meeting has not been processed."
      />
    )
  }

  return (
    <div className="space-y-6 p-5">
      <section>
        <SectionTitle icon={<Sparkles size={14} />}>Overview</SectionTitle>
        <p className="text-[15px] leading-relaxed text-ink-soft">{summary.overview}</p>
        <div className="mt-3 flex flex-wrap gap-1.5">
          {summary.topics.map((topic) => (
            <Badge key={topic} tone="accent">
              {topic}
            </Badge>
          ))}
        </div>
      </section>

      {summary.key_points.length > 0 && (
        <section>
          <SectionTitle icon={<ListChecks size={14} />}>Key points</SectionTitle>
          <ul className="space-y-2">
            {summary.key_points.map((point) => (
              <li key={point} className="flex gap-2.5 text-sm leading-relaxed text-ink-soft">
                <span className="mt-2 size-1.5 shrink-0 rounded-full bg-ink-faint" />
                {point}
              </li>
            ))}
          </ul>
        </section>
      )}

      {summary.decisions.length > 0 && (
        <section>
          <SectionTitle icon={<CircleCheck size={14} />}>Decisions</SectionTitle>
          <ul className="space-y-2">
            {summary.decisions.map((decision) => (
              <li
                key={decision}
                className="rounded-lg border border-line bg-canvas px-3 py-2.5 text-sm leading-relaxed text-ink-soft"
              >
                {decision}
              </li>
            ))}
          </ul>
        </section>
      )}

      {summary.insights.length > 0 && (
        <section>
          <SectionTitle icon={<Lightbulb size={14} />}>AI insights</SectionTitle>
          <ul className="space-y-2.5">
            {summary.insights.map((insight) => (
              <li
                key={insight}
                className="border-l-2 border-accent/40 pl-3 text-sm leading-relaxed text-ink-soft"
              >
                {insight}
              </li>
            ))}
          </ul>
        </section>
      )}

      <p className="border-t border-line pt-3 text-xs text-ink-faint">
        {summary.generated_by === 'llm'
          ? 'Generated by the configured language model.'
          : 'Generated without an LLM key, using the built-in fallback summariser.'}
      </p>
    </div>
  )
}

function SectionTitle({ icon, children }: { icon: React.ReactNode; children: React.ReactNode }) {
  return (
    <h3 className="mb-2.5 flex items-center gap-1.5 text-[11px] font-semibold tracking-wider text-ink-faint uppercase">
      {icon}
      {children}
    </h3>
  )
}
